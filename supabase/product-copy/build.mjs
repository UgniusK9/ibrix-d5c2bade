// Builds supabase/migrations/20261005000000_rewrite_product_copy.sql from batch-*.json.
// Run: node supabase/product-copy/build.mjs   (exits non-zero if any entry breaks a rule)
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const out = join(dir, '..', 'migrations', '20261005000000_rewrite_product_copy.sql');
const FIELDS = ['short', 'desc', 'title_en', 'short_en', 'desc_en'];
const SHIP = ' Nemokamas pristatymas į paštomatą.';
// Lithuanian: after numbers ending in 1 (but not 11) the noun is singular genitive: 321 detalės, not 321 detalių.
const fixLt = (s) => s.replace(/(\d[\d ]*) (detalių)/g, (m, num) => { const n = parseInt(num.replace(/ /g, ''), 10); return n % 10 === 1 && n % 100 !== 11 ? `${num} detalės` : m; });
const nbsp = (s) => s.replace(/(\d) (\d{3})(?!\d)/g, '$1 $2').replace(/(\d) (detal|dalių|pcs|pieces)/g, '$1 $2');

const rows = [];
const errors = [];
const seen = new Set();
for (const f of readdirSync(dir).filter((n) => /^batch-[a-z0-9]+\.json$/.test(n)).sort()) {
  for (const p of JSON.parse(readFileSync(join(dir, f), 'utf8'))) {
    const at = `${f} ${p.sku}`;
    if (seen.has(p.sku)) errors.push(`${at}: duplicate sku`);
    seen.add(p.sku);
    for (const k of FIELDS) {
      const v = p[k];
      if (typeof v !== 'string' || v.trim().length < 10) errors.push(`${at}: ${k} missing`);
      else if (/[—–]/.test(v)) errors.push(`${at}: ${k} has a dash`);
      else if (/\$c\$/.test(v)) errors.push(`${at}: ${k} breaks quoting`);
    }
    if (p.desc && (p.desc.length < 140 || p.desc.length > 650)) errors.push(`${at}: desc length ${p.desc.length}`);
    if (p.desc_en && (p.desc_en.length < 140 || p.desc_en.length > 650)) errors.push(`${at}: desc_en length ${p.desc_en.length}`);
    if (p.short && p.short.length > 140) errors.push(`${at}: short too long (${p.short.length})`);
    if (errors.length && errors[errors.length - 1].startsWith(at)) continue;
    const t = (s) => nbsp(s.trim());
    const short = t(fixLt(p.short));
    const meta = short.length + SHIP.length <= 160 ? short + SHIP : short;
    rows.push([p.sku, short, t(fixLt(p.desc)), t(p.title_en), t(p.short_en), t(p.desc_en), meta]);
  }
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const q = (s) => `$c$${s}$c$`;
const sql = String.raw`-- Rewritten product copy (LT + EN). Requires 20260914000000_add_product_en_fields.sql first.
-- Generated by supabase/product-copy/build.mjs, do not edit by hand.
BEGIN;

UPDATE public.products AS p SET
  short_desc = v.short, description = v.descr, title_en = v.title_en,
  short_desc_en = v.short_en, description_en = v.desc_en, meta_description = v.meta
FROM (VALUES
${rows.map((r) => `  (${r.map(q).join(', ')})`).join(',\n')}
) AS v(sku, short, descr, title_en, short_en, desc_en, meta)
WHERE p.sku = v.sku;

-- meta_title: the site appends " | IBRIX", so keep this to 52 chars, cut at a word boundary.
-- "Remote Controlled" becomes "RC" so long English names keep their noun.
UPDATE public.products SET meta_title = (
  WITH b AS (SELECT btrim(regexp_replace(regexp_replace(regexp_replace(regexp_replace(title,
    '\s*\|.*$', ''), '\s+(Kaladėlių\s+)?Konstruktorius$', ''), 'Remote[- ]Controlled', 'RC', 'gi'), '\s{2,}', ' ', 'g')) AS base)
  SELECT CASE
    WHEN length(base || ' konstruktorius') <= 52 THEN base || ' konstruktorius'
    WHEN length(base) <= 52 THEN base
    ELSE regexp_replace(left(base, 53), '\s+\S*$', '')
  END FROM b
) WHERE status = 'active' AND title IS NOT NULL;

COMMIT;
`;
writeFileSync(out, sql);
console.log(`ok: ${rows.length} products -> ${out}`);
